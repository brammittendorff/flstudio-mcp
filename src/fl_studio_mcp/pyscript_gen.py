"""Generate a piano-roll .pyscript with notes baked in.

File I/O is blocked inside FL's pyscript sandbox (BOTH read and write on FL
25.2.5 -- confirmed by probe). So we can't hand note data to a generic script
via a job file. Instead the daemon (a normal process, which CAN write files)
GENERATES the .pyscript itself with the notes embedded as a Python literal,
writes it to FL's "Piano roll scripts" folder, and triggers it. FL re-reads
the file on each trigger (confirmed), so overwrite + re-trigger applies fresh
notes. The script only ever calls addNote -- no file I/O inside FL.

Notes are specified in musical units (bars); the GENERATED script converts to
ticks at runtime using the live score.PPQ, so it's PPQ-agnostic.
"""

from __future__ import annotations

import os

from .paths import fl_settings_dir

PIANO_ROLL_SCRIPTS_DIR = str(fl_settings_dir() / "Piano roll scripts")
APPLY_SCRIPT_NAME = "MCP_Apply.pyscript"

_DEFAULT_VELOCITY = 100 / 127.0

_TEMPLATE = '''# Script.Name = "MCP Apply"
# Script.Category = "MCP"
# AUTO-GENERATED by fl-studio-mcp. Do not edit -- overwritten on each apply.

import flpianoroll as flp

MODE = {mode!r}        # "replace" clears the pattern first; "append" adds
NOTES = {notes!r}      # (pitch, time_bars, length_bars, velocity 0..1)


def _run():
    score = flp.score
    bar = score.PPQ * 4
    if MODE == "replace":
        try:
            score.clearNotes(True)     # FL 25.2.5: positional, no keyword
        except TypeError:
            score.clearNotes()
    for pitch, t_bars, len_bars, vel in NOTES:
        n = flp.Note()
        n.number = int(pitch)
        n.time = int(round(t_bars * bar))
        n.length = max(1, int(round(len_bars * bar)))
        n.velocity = float(vel)
        score.addNote(n)


def _go():
    undo = getattr(flp.score, "undoSection", None)
    if callable(undo):
        try:
            with undo():
                _run()
            return
        except Exception:
            pass
    _run()


_go()
'''


def render_apply_script(notes, mode="replace"):
    """Return the .pyscript source text for the given notes.

    notes: iterable of dicts {pitch, time_bars, length_bars, velocity}.
    """
    tuples = []
    for n in notes:
        tuples.append((
            int(n["pitch"]),
            float(n.get("time_bars", 0.0)),
            float(n.get("length_bars", 1.0)),
            float(n.get("velocity", _DEFAULT_VELOCITY)),
        ))
    return _TEMPLATE.format(mode=mode, notes=tuples)


def write_apply_script(notes, mode="replace", scripts_dir=None):
    """Write the generated apply-script into FL's Piano roll scripts folder.

    Returns the path written.
    """
    scripts_dir = scripts_dir or PIANO_ROLL_SCRIPTS_DIR
    text = render_apply_script(notes, mode)
    path = os.path.join(scripts_dir, APPLY_SCRIPT_NAME)
    with open(path, "w", encoding="ascii") as f:
        f.write(text)
    return path


# ---------------------------------------------------------------------------
# Quantize
# ---------------------------------------------------------------------------

def quantize_notes(notes, grid_bars, snap_ends=False):
    """Snap each note's start (and optionally length) to a grid, in BARS. PURE.

    grid_bars: 0.0625 = 1/16, 0.125 = 1/8, 0.25 = 1/4. grid_bars <= 0 -> unchanged.
    Used to quantize notes we GENERATE before writing them.
    """
    g = float(grid_bars or 0)
    if g <= 0:
        return [dict(n) for n in notes]
    out = []
    for n in notes:
        m = dict(n)
        m["time_bars"] = round(round(float(n.get("time_bars", 0.0)) / g) * g, 6)
        if snap_ends:
            m["length_bars"] = max(g, round(round(float(n.get("length_bars", g)) / g) * g, 6))
        out.append(m)
    return out


# Quantizes the notes ALREADY in the open piano roll: read every note, clear,
# re-add with start (and optionally length) snapped to the grid. Uses the same
# addNote path the apply script proved works. PPQ-agnostic (uses live score.PPQ).
_QUANTIZE_TEMPLATE = '''# Script.Name = "MCP Apply"
# Script.Category = "MCP"
# AUTO-GENERATED by fl-studio-mcp (quantize). Do not edit -- overwritten.

import flpianoroll as flp

GRID_BARS = {grid!r}     # snap resolution in bars (0.0625 = 1/16)
SNAP_ENDS = {ends!r}     # also snap note lengths to the grid


def _run():
    score = flp.score
    step = max(1, int(round(GRID_BARS * score.PPQ * 4)))
    notes = []
    for i in range(score.noteCount):
        n = score.getNote(i)
        notes.append((n.number, n.time, n.length, n.velocity))
    if not notes:
        return
    try:
        score.clearNotes(True)
    except TypeError:
        score.clearNotes()
    for num, t, ln, vel in notes:
        m = flp.Note()
        m.number = num
        m.time = int(round(t / step) * step)
        m.length = max(step, int(round(ln / step) * step)) if SNAP_ENDS else ln
        m.velocity = vel
        score.addNote(m)


def _go():
    undo = getattr(flp.score, "undoSection", None)
    if callable(undo):
        try:
            with undo():
                _run()
            return
        except Exception:
            pass
    _run()


_go()
'''


def render_quantize_script(grid_bars, snap_ends=False):
    return _QUANTIZE_TEMPLATE.format(grid=float(grid_bars), ends=bool(snap_ends))


# ---------------------------------------------------------------------------
# Groove: swing + humanize
# ---------------------------------------------------------------------------

def groove(notes, swing=0.0, grid=0.0625, timing=0.0, velocity=0.0, seed=1):
    """Swing and humanize (pitch, time, length, vel) tuples, times in bars. PURE.

    swing: 0..1, delays every off-beat note on the grid (1.0 = triplet swing).
    timing: max random start shift in bars. velocity: max relative change.
    Self-contained (no imports) because its source also runs inside FL's
    piano roll script, so new and existing notes get the same groove.
    """
    state = [(int(seed) & 0x7FFFFFFF) or 1]

    def rnd():                                     # -1..1, same sequence everywhere
        state[0] = (state[0] * 1103515245 + 12345) & 0x7FFFFFFF
        return state[0] / 1073741823.5 - 1.0

    out = []
    for pitch, t, length, vel in notes:
        if swing and grid > 0:
            step = round(t / grid)
            if step % 2 == 1 and abs(t - step * grid) < grid * 0.25:
                t += swing * grid / 3.0
        if timing:
            t = max(0.0, t + rnd() * timing)
        if velocity:
            vel = min(1.0, max(0.05, vel * (1.0 + rnd() * velocity)))
        out.append((pitch, t, length, vel))
    return out


def groove_notes(notes, swing=0.0, grid=0.0625, timing=0.0, velocity=0.0, seed=1):
    """groove() for note dicts {pitch, time_bars, length_bars, velocity}."""
    tuples = [(n["pitch"], float(n.get("time_bars", 0.0)), float(n.get("length_bars", 1.0)),
               float(n.get("velocity", _DEFAULT_VELOCITY))) for n in notes]
    return [{"pitch": p, "time_bars": round(t, 6), "length_bars": ln, "velocity": round(v, 4)}
            for p, t, ln, v in groove(tuples, swing, grid, timing, velocity, seed)]


# Grooves the notes ALREADY in the open piano roll, with groove()'s own source.
_GROOVE_TEMPLATE = '''# Script.Name = "MCP Apply"
# Script.Category = "MCP"
# AUTO-GENERATED by fl-studio-mcp (groove). Do not edit -- overwritten.

import flpianoroll as flp

{func}

ARGS = {args!r}


def _run():
    score = flp.score
    bar = float(score.PPQ * 4)
    notes = []
    for i in range(score.noteCount):
        n = score.getNote(i)
        notes.append((n.number, n.time / bar, n.length, n.velocity))
    if not notes:
        return
    try:
        score.clearNotes(True)
    except TypeError:
        score.clearNotes()
    for num, t, ln, vel in groove(notes, **ARGS):
        m = flp.Note()
        m.number = num
        m.time = int(round(t * bar))
        m.length = ln
        m.velocity = vel
        score.addNote(m)


def _go():
    undo = getattr(flp.score, "undoSection", None)
    if callable(undo):
        try:
            with undo():
                _run()
            return
        except Exception:
            pass
    _run()


_go()
'''


def render_groove_script(swing=0.0, grid=0.0625, timing=0.0, velocity=0.0, seed=1):
    import inspect
    args = {"swing": float(swing), "grid": float(grid), "timing": float(timing),
            "velocity": float(velocity), "seed": int(seed)}
    return _GROOVE_TEMPLATE.format(func=inspect.getsource(groove), args=args)


def write_groove_script(scripts_dir=None, **kwargs):
    """Write the groove-existing-notes script to MCP_Apply.pyscript. Returns path."""
    scripts_dir = scripts_dir or PIANO_ROLL_SCRIPTS_DIR
    path = os.path.join(scripts_dir, APPLY_SCRIPT_NAME)
    with open(path, "w", encoding="ascii") as f:
        f.write(render_groove_script(**kwargs))
    return path


def write_quantize_script(grid_bars, snap_ends=False, scripts_dir=None):
    """Write the quantize-existing-notes script to MCP_Apply.pyscript. Returns path."""
    scripts_dir = scripts_dir or PIANO_ROLL_SCRIPTS_DIR
    text = render_quantize_script(grid_bars, snap_ends)
    path = os.path.join(scripts_dir, APPLY_SCRIPT_NAME)
    with open(path, "w", encoding="ascii") as f:
        f.write(text)
    return path
